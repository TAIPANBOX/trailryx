def main() -> None:
    seen: set[str] = set()
    out = sys.stdout
    for name, raw, verdict in CASES:
        # A duplicated name would not be a cosmetic problem. Every consumer of
        # this corpus keys on the name, so the second copy would replace the
        # first and the corpus would quietly be one case smaller than it says.
        if name in seen:
            raise SystemExit(f"duplicate case name: {name}")
        seen.add(name)
        if verdict not in ("y", "n", "i"):
            raise SystemExit(f"{name}: verdict must be y, n or i, not {verdict!r}")
        if not name.startswith(verdict + "_"):
            raise SystemExit(f"{name}: name prefix disagrees with verdict {verdict!r}")
        out.write(f"{name}\t{raw.hex()}\t{verdict}\n")


if __name__ == "__main__":
    main()
