#!/usr/bin/env python3
"""Write the conformance corpus to stdout as TSV: name, hex, verdict.

The bytes are hex-encoded because a corpus stored as text loses exactly the
cases that matter. Invalid UTF-8 cannot round-trip through a text file at all, a
NUL byte is dropped or truncated by half the tools that would touch the file,
and a byte-order mark is silently eaten by editors. Hex survives all three, and
it also survives being pasted into a bug report.

`verdict` is what RFC 8259 requires of any parser, not what trailryx does:

    y   a conforming parser must accept these bytes
    n   a conforming parser must reject these bytes
    i   the grammar is satisfied but the answer is implementation-defined,
        because a bound, a numeric range or a lone surrogate is involved

Case names follow the JSONTestSuite convention (prefix `y_`, `n_` or `i_`
matching the verdict, then a descriptive tail) so a name can be compared against
the upstream corpus by eye. What trailryx is expected to do with each case lives
in EXPECTATIONS.tsv, deliberately in a separate file: the RFC verdict and our
verdict are different claims and merging them would hide the three places we
knowingly diverge.

Every case here is hand-written from a named divergence class in "Parsing JSON
is a Minefield". Nothing is generated by fuzzing: a fuzzer finds bytes nobody
can explain, and a corpus whose cases nobody can explain stops being maintained.
"""

import sys

# One entry per case. Built as a list rather than a dict so the file reads in
# class order and so a duplicated name is caught by the check at the bottom
# instead of silently replacing its twin and shrinking the corpus.
CASES: list[tuple[str, bytes, str]] = []


def case(name: str, raw: bytes, verdict: str) -> None:
    CASES.append((name, raw, verdict))


def nested_arrays(n: int) -> bytes:
    """`n` arrays, properly closed."""
    return b"[" * n + b"]" * n


def object_of(n: int) -> bytes:
    """One object with `n` distinct members, to sit either side of a bound."""
    members = b",".join(b'"k%d":%d' % (i, i) for i in range(n))
    return b"{" + members + b"}"


def digits(n: int) -> bytes:
    """An integer literal of exactly `n` digits, no leading zero."""
    return b"1" + b"0" * (n - 1)


